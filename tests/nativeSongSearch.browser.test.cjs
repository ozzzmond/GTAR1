const test = require('node:test')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const os = require('node:os')
const { chromium } = require('playwright')

test('native search boundary: offline local dropdown, keyboard, responsive layout and explicit validated import', { timeout: 120000 }, async () => {
  const { createServer } = await import('vite')
  const cacheDir = fs.mkdtempSync(path.join(os.tmpdir(), 'gtar1-dev17-'))
  let server, browser
  try {
    server = await createServer({ root: path.resolve(__dirname, '..'), cacheDir, logLevel: 'error', server: { host: '127.0.0.1', port: 0 } })
    await server.listen()
    const origin = `http://127.0.0.1:${server.httpServer.address().port}`
    for (const channel of ['msedge', 'chrome', undefined]) {
      try { browser = await chromium.launch({ headless: true, ...(channel ? { channel } : {}) }); break }
      catch (error) { if (!channel) throw error }
    }
    for (const width of [1440, 390, 320]) {
      const context = await browser.newContext({ viewport: { width, height: 844 }, hasTouch: width < 640 })
      const page = await context.newPage()
      const errors = [], remoteRequests = []
      page.on('pageerror', error => errors.push(error.message))
      page.on('request', request => { if (!request.url().startsWith(origin) || /\/api\//.test(request.url())) remoteRequests.push(request.url()) })
      await page.goto(origin)
      await page.locator('header').first().getByRole('button', { name: 'New Song', exact: true }).waitFor()
      await page.evaluate(async () => {
        const store = await import('/src/utils/storage.ts')
        await store.saveSong({ id: 'owned', title: 'Owned chart', artist: 'Local musician', format: 'CHORD_PRO', rawContent: '[C]Hello', tags: ['Fixture'], createdAt: 1, updatedAt: 1 })
        await store.saveSetlist({ id: 'gig', name: 'Owned Gig', songs: [], createdAt: 1, updatedAt: 1 })
      })
      await page.reload()
      await page.locator('main').getByText('Owned chart', { exact: true }).waitFor()
      await context.setOffline(true)
      const input = page.getByLabel('Global search', { exact: true })
      const focusSearch = async () => {
        if (width < 640 && !await input.isVisible()) await page.getByRole('button', { name: 'Open search', exact: true }).click()
        await input.focus()
      }
      await focusSearch()
      await input.fill('Owned')
      const results = page.getByRole('region', { name: 'Search results', exact: true })
      await results.getByRole('button', { name: 'Owned chart Local musician' }).waitFor()
      assert.equal(await results.getByRole('button', { name: 'Owned Gig 0 songs' }).count(), 1)
      assert.equal(await results.getByRole('button', { name: 'Native online search unavailable' }).isDisabled(), true)
      const box = await results.boundingBox()
      assert.ok(box.x >= 0 && box.x + box.width <= width, `Dropdown fits ${width}`)
      assert.ok(await page.locator('header').first().evaluate(el => el.offsetHeight <= 65), 'Header stays compact')
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      await input.press('ArrowDown')
      await page.waitForFunction(() => document.activeElement?.closest('#global-search-results') && document.activeElement.tagName === 'BUTTON')
      assert.equal(await results.getByRole('button', { name: 'Owned chart Local musician' }).evaluate(el => el === document.activeElement), true)
      await page.keyboard.press('Escape')
      assert.equal(await input.evaluate(el => el === document.activeElement), true)
      assert.equal(await results.count(), 0)
      await input.press('Escape')
      assert.equal(await input.inputValue(), '')
      await input.fill('Gig')
      await results.getByRole('button', { name: 'Owned Gig 0 songs' }).click()
      await page.locator('main').getByText('Owned Gig', { exact: true }).first().waitFor()
      await focusSearch()
      await input.fill('Owned')
      await results.getByRole('button', { name: 'Owned chart Local musician' }).click()
      await page.getByRole('button', { name: 'Back to Songbook' }).waitFor()
      await focusSearch()
      await input.fill('Owned')
      await results.getByRole('button', { name: 'Preview & Import a chart' }).click()
      const dialog = page.getByRole('dialog', { name: 'Browse Song Sources', exact: true })
      const text = dialog.locator('#import-raw-text-input')
      await text.fill('<script>alert(1)</script>')
      await dialog.getByRole('button', { name: 'Preview Chart', exact: true }).click()
      await dialog.getByRole('alert').filter({ hasText: 'HTML pages are not chord charts' }).waitFor()
      await text.fill('{title: Owned chart}\n{artist: Local musician}\n[tab][ch]C[/ch]Hello world[/tab]')
      await dialog.getByRole('button', { name: 'Preview Chart', exact: true }).click()
      await dialog.getByRole('alert').filter({ hasText: 'Duplicate Title Detected' }).waitFor()
      const records = () => page.evaluate(async () => (await import('/src/utils/storage.ts')).loadAllSongs())
      assert.equal((await records()).length, 1, 'Preview never persists')
      await dialog.getByRole('button', { name: 'Save to Local Songbook', exact: true }).click()
      await dialog.getByRole('alert').filter({ hasText: 'Choose Save as Copy' }).last().waitFor()
      assert.equal((await records()).length, 1, 'Duplicate fails safely')
      await dialog.getByRole('button', { name: 'Save as Copy', exact: true }).click()
      await dialog.locator('#preview-title').fill('Unsafe\n{key: D}')
      await dialog.getByRole('button', { name: 'Save to Local Songbook', exact: true }).click()
      await dialog.getByRole('alert').filter({ hasText: 'Metadata must' }).waitFor()
      await dialog.locator('#preview-title').fill('Owned chart (Copy)')
      await dialog.getByRole('button', { name: 'Save to Local Songbook', exact: true }).click()
      await dialog.waitFor({ state: 'hidden' })
      const saved = (await records()).find(song => song.title === 'Owned chart (Copy)')
      assert.ok(saved)
      assert.match(saved.rawContent, /\[C\]Hello world/)
      assert.equal((await records()).length, 2)
      await context.setOffline(false)
      await page.reload()
      await page.locator('header').first().getByRole('button', { name: 'New Song', exact: true }).waitFor()
      assert.equal((await records()).length, 2, 'Import persists after reload')
      assert.deepEqual(errors, [])
      assert.deepEqual(remoteRequests, [], 'No startup/search/preview retrieval requests')
      await context.close()
    }
  } finally {
    await browser?.close()
    await server?.close()
    fs.rmSync(cacheDir, { recursive: true, force: true })
  }
})
