const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { chromium } = require('playwright')

async function launchBrowser() {
  for (const channel of ['msedge', 'chrome', undefined]) {
    try { return await chromium.launch({ headless: true, ...(channel ? { channel } : {}) }) }
    catch (error) { if (!channel) throw error }
  }
}

test('unified search: local filtering, explicit provider navigation, shared settings and responsive scope state', { timeout: 120000 }, async () => {
  const { createServer } = await import('vite')
  const cacheDir = fs.mkdtempSync(path.join(os.tmpdir(), 'gtar1-unified-search-'))
  let server, browser
  try {
    server = await createServer({ root: path.resolve(__dirname, '..'), cacheDir, logLevel: 'error', server: { host: '127.0.0.1', port: 0 }, clearScreen: false })
    await server.listen()
    const origin = `http://127.0.0.1:${server.httpServer.address().port}`
    browser = await launchBrowser()
    for (const viewport of [{ width: 1440, height: 900 }, { width: 768, height: 1024 }, { width: 375, height: 667 }]) {
      const context = await browser.newContext({ viewport })
      const page = await context.newPage()
      const errors = [], externalRequests = []
      page.on('pageerror', error => errors.push(error.message))
      await context.route(/^https:\/\//, async route => {
        externalRequests.push(route.request().url())
        await route.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html><title>Provider website fixture</title>' })
      })
      await page.goto(origin)
      await page.getByLabel('Global search', { exact: true }).waitFor()
      await page.evaluate(async () => {
        const core = await import('/src/utils/storage.ts')
        for (const [id, title] of [['unified-alpha', 'Alpha Grace'], ['unified-beta', 'Beta Song']]) {
          await core.saveSong({ id, title, artist:'Local musician', format:'CHORD_PRO', rawContent:'[G]Local chart', tags:[], createdAt:1, updatedAt:1 })
        }
        await core.saveSetlist({ id:'unified-gig', name:'Unified Gig', songs:[], createdAt:1, updatedAt:1 })
      })
      await page.reload()
      const main = page.locator('main[data-explorer-canvas]')
      await main.getByText('Alpha Grace', { exact:true }).waitFor()
      const records = () => page.evaluate(async () => {
        const core = await import('/src/utils/storage.ts')
        return [await core.loadAllSongs(), await core.loadAllSetlists()]
      })
      const before = await records()
      const query = page.getByLabel('Global search', { exact:true })
      const scope = page.getByLabel('Search scope', { exact:true })
      const provider = page.getByRole('combobox', { name:'Online provider', exact:true })
      const globalForm = page.getByRole('search', { name:'Global song search' })
      const openSources = () => page.getByRole('button', { name:'Browse Song Sources', exact:true }).click()
      assert.equal(await scope.inputValue(), 'MY_SONGS')
      await query.fill('Alpha')
      await main.getByText('Alpha Grace', { exact:true }).waitFor()
      assert.equal(await main.getByText('Beta Song', { exact:true }).count(), 0)
      await query.press('Enter')
      assert.equal(await scope.inputValue(), 'MY_SONGS')
      await context.setOffline(true)
      await query.fill('Beta')
      await main.getByText('Beta Song', { exact:true }).waitFor()
      assert.equal(await main.getByText('Alpha Grace', { exact:true }).count(), 0)
      await scope.selectOption('ONLINE_SOURCES')
      assert.equal(await query.inputValue(), 'Beta')
      assert.equal(await provider.inputValue(), 'ultimate_guitar')
      await query.fill('Alpha')
      assert.equal(await main.getByText('Alpha Grace', { exact:true }).count(), 0, 'Online edits do not alter local results')
      await main.getByText('Beta Song', { exact:true }).waitFor()
      await query.press('Enter')
      await globalForm.getByRole('alert').filter({ hasText:'You are offline' }).waitFor()
      assert.deepEqual(externalRequests, [])
      await scope.selectOption('MY_SONGS')
      assert.equal(await query.inputValue(), 'Alpha')
      await main.getByText('Alpha Grace', { exact:true }).waitFor()
      assert.equal(await main.getByText('Beta Song', { exact:true }).count(), 0)
      await query.press('Escape')
      assert.equal(await query.inputValue(), '')
      await main.getByText('Beta Song', { exact:true }).waitFor()
      await query.press('Escape')
      assert.equal(await query.evaluate(el => el === document.activeElement), false)
      await context.setOffline(false)
      await scope.selectOption('ONLINE_SOURCES')
      await query.press('Enter')
      await globalForm.getByRole('alert').filter({ hasText:'Enter a song or artist' }).waitFor()
      const term = 'Amazing Grace & John Newton'
      await query.fill(term)
      assert.deepEqual(externalRequests, [], 'Typing and scope changes never contact providers')
      const openProvider = async action => {
        const [popup] = await Promise.all([context.waitForEvent('page'), action()])
        await popup.waitForLoadState('domcontentloaded')
        assert.equal(await popup.evaluate(() => window.opener), null)
        const result = new URL(popup.url())
        await popup.close()
        return result
      }
      let url = await openProvider(() => query.press('Enter'))
      assert.equal(url.hostname, 'www.ultimate-guitar.com')
      assert.equal(url.pathname, '/search.php')
      assert.equal(url.searchParams.get('value'), term)
      await provider.selectOption('chordie')
      assert.equal(await query.inputValue(), term)
      url = await openProvider(() => globalForm.getByRole('button', { name:'Search Online', exact:true }).click())
      assert.equal(url.hostname, 'www.chordie.com')
      assert.equal(url.pathname, '/result.php')
      assert.equal(url.searchParams.get('q'), term)
      for (const [id, host] of [['songselect', 'songselect.ccli.com'], ['opmtunes', 'www.opmtunes.com']]) {
        await provider.selectOption(id)
        assert.equal(await query.inputValue(), term)
        assert.equal(await globalForm.getByRole('button', { name:'Search Online', exact:true }).count(), 0)
        url = await openProvider(() => globalForm.getByRole('button', { name:'Open Website', exact:true }).click())
        assert.equal(url.hostname, host)
        assert.equal(url.pathname, '/')
        assert.equal(url.search, '')
      }
      assert.equal(externalRequests.length, 4)
      // The Sources dialog is management/import only; its selection updates the same header preference.
      await openSources()
      const dialog = page.getByRole('dialog', { name:'Browse Song Sources', exact:true })
      assert.equal(await page.locator('#online-source-query').count(), 0)
      await dialog.getByLabel('Provider', { exact:true }).selectOption('chordie')
      assert.equal(await provider.inputValue(), 'chordie')
      await dialog.getByRole('button', { name:'Manual import', exact:true }).first().click()
      await page.locator('#import-raw-text-input').waitFor()
      await page.getByRole('tab', { name:'Browse Websites', exact:true }).click()
      await dialog.getByRole('button', { name:'Use header search', exact:true }).click()
      assert.equal(await query.inputValue(), term)
      assert.equal(await query.evaluate(el => el === document.activeElement), true)
      await query.fill('Beta')
      await scope.selectOption('MY_SONGS')
      await main.getByText('Beta Song', { exact:true }).waitFor()
      assert.equal(await main.getByText('Alpha Grace', { exact:true }).count(), 0)
      await page.getByRole('button', { name:'Clear search query', exact:true }).click()
      assert.equal(await query.inputValue(), '')
      await main.getByText('Alpha Grace', { exact:true }).waitFor()
      // Navigation and theme dialog must not reset the query or scope.
      await query.fill('Beta')
      await main.getByText('Beta Song', { exact:true }).click()
      await page.getByRole('button', { name:'Edit Song', exact:true }).waitFor()
      assert.equal(await query.inputValue(), 'Beta')
      await page.getByTitle('Enter Stage Performance Mode (Alt+1)').click()
      await page.locator('[data-stage-canvas="true"]').waitFor()
      await page.getByRole('button', { name:/Exit Stage/ }).click()
      await query.waitFor()
      assert.equal(await query.inputValue(), 'Beta')
      assert.equal(await scope.inputValue(), 'MY_SONGS')
      await page.getByRole('button', { name:/Musician Profile:/ }).click()
      await page.getByTestId('header-theme-settings-btn').click()
      await page.getByRole('button', { name:'Close without saving', exact:true }).click()
      assert.equal(await query.inputValue(), 'Beta')
      await scope.selectOption('ONLINE_SOURCES')
      assert.equal(await provider.inputValue(), 'chordie')
      for (const control of [scope, query, provider, globalForm.getByRole('button', { name:'Search Online', exact:true })]) {
        const bounds = await control.boundingBox()
        assert.ok(bounds.height >= 44)
        assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= viewport.width + 1)
      }
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Header fits desktop/tablet/mobile')
      if (process.env.GTAR1_SOURCES_VISUAL_QA) await page.screenshot({ path:path.join(os.tmpdir(), `gtar1-unified-search-${viewport.width}.png`) })
      const saved = await page.evaluate(() => localStorage.getItem('gtar1_song_source_provider'))
      assert.equal(saved, 'chordie')
      await page.reload()
      await query.waitFor()
      assert.equal(await scope.inputValue(), 'MY_SONGS', 'Scope is session-only')
      assert.equal(await query.inputValue(), '', 'Query is not persisted')
      await scope.selectOption('ONLINE_SOURCES')
      assert.equal(await provider.inputValue(), 'chordie')
      assert.equal(externalRequests.length, 4)
      assert.deepEqual(await records(), before)
      assert.deepEqual(errors, [])
      await context.close()
    }
  } finally {
    if (browser) await browser.close()
    if (server) await server.close()
    fs.rmSync(cacheDir, { recursive:true, force:true })
  }
})
